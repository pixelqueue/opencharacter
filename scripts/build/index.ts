import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { parse as parseYaml } from 'yaml';
import { buildRelease, type PackRelease } from '../../packages/engine/src/index.ts';
import { parse, print, type Node } from '../../packages/engine/src/formula/index.ts';
import { validateRepo } from '../validate/index.ts';
import type { LoadedPack } from '../validate/load.ts';
import type { Reporter } from '../validate/report.ts';
import type { I18nDoc } from '../validate/types.ts';

// Pack source → release JSON, per-language translation entry points, and the
// @opencharacter/packs bundle (packages/spec/docs/packs.md, "Releases").

export interface CompiledFormula {
  /** Canonical text (the printer's layout). */
  text: string;
  tree: Node;
}

export interface BuiltPack {
  id: string;
  dir: string;
  release: PackRelease & { formulas: Record<string, CompiledFormula> };
  /** Translations by language, split files merged. */
  i18n: Record<string, I18nDoc>;
  defaultLanguage: string;
}

export interface BuildResult {
  reporter: Reporter;
  built: BuiltPack[];
}

/**
 * Validates every pack (the build refuses invalid packs), then builds each into its release.
 * The release carries formulas as written plus a `formulas` table: source text → canonical text
 * and parsed tree, so ports can walk trees without a parser.
 */
export function buildPacks(root: string): BuildResult {
  const formulas = new Map<string, Set<string>>();
  const { reporter, loaded } = validateRepo(root, {
    onFormula: (id, text) => {
      const set = formulas.get(id) ?? new Set<string>();
      set.add(text);
      formulas.set(id, set);
    },
  });
  if (reporter.errors.length > 0) return { reporter, built: [] };
  const built = loaded.map((pack) =>
    buildPack(resolve(root), pack, formulas.get(pack.manifest.id) ?? new Set()),
  );
  return { reporter, built };
}

function buildPack(root: string, pack: LoadedPack, texts: Set<string>): BuiltPack {
  const compiled: Record<string, CompiledFormula> = {};
  for (const text of [...texts].toSorted()) {
    const tree = parse(text);
    if (tree.ok) compiled[text] = { text: print(tree.value), tree: tree.value };
  }
  const release = buildRelease({
    manifest: pack.manifest,
    // A release has no family keys; `families` stays for formulas.
    rules: pack.rules.map((r) => r.doc),
    content: pack.content.map((c) => c.doc),
    upgrades: pack.upgrades.map((u) => u.doc),
  });
  const i18n: Record<string, I18nDoc> = {};
  for (const [language, files] of pack.i18n) {
    i18n[language] = Object.assign({}, ...files.map((f) => f.doc)) as I18nDoc;
  }
  return {
    id: pack.manifest.id,
    dir: join(root, pack.dir),
    release: { ...release, formulas: compiled },
    i18n,
    defaultLanguage: pack.manifest.defaultLanguage,
  };
}

const json = (data: unknown) => `${JSON.stringify(data, null, 2)}\n`;
const module = (data: unknown) =>
  `// Generated by pnpm build:packs. Do not edit.\nexport default ${JSON.stringify(data)};\n`;
const declaration = (type: string) =>
  `// Generated by pnpm build:packs. Do not edit.\ndeclare const value: ${type};\nexport default value;\n`;

/**
 * Writes a built pack's files:
 * - `dist/release.json` and `dist/index.js` (the mechanics package's entry point);
 * - `dist/i18n/<default language>.{json,js}` (opt-in entry point in the same package);
 * - other languages into the pack's `-i18n` package (`i18n-package/dist/<lang>.{json,js}`),
 *   which must exist (it has its own version, so translation fixes never bump the pack).
 * Returns problems; writes nothing for a pack with problems.
 */
export function writePack(pack: BuiltPack): string[] {
  const others = Object.keys(pack.i18n).filter((l) => l !== pack.defaultLanguage);
  const i18nPackage = join(pack.dir, 'i18n-package');
  if (others.length > 0 && !existsSync(join(i18nPackage, 'package.json'))) {
    return [
      `${pack.id}: has translations (${others.join(', ')}) but no -i18n package. Create ${join(i18nPackage, 'package.json')} with ` +
        `{ "name": "@opencharacter/${pack.id}-i18n", "version": "0.1.0", "private": true, "exports": { "./*": { "import": "./dist/*.js", "default": "./dist/*.json" } } }`,
    ];
  }
  const dist = join(pack.dir, 'dist');
  rmSync(dist, { recursive: true, force: true });
  mkdirSync(join(dist, 'i18n'), { recursive: true });
  writeFileSync(join(dist, 'release.json'), json(pack.release));
  writeFileSync(join(dist, 'index.js'), module(pack.release));
  writeFileSync(
    join(dist, 'index.d.ts'),
    declaration("import('@opencharacter/engine').PackRelease"),
  );
  const defaults = pack.i18n[pack.defaultLanguage] ?? {};
  writeFileSync(join(dist, 'i18n', `${pack.defaultLanguage}.json`), json(defaults));
  writeFileSync(join(dist, 'i18n', `${pack.defaultLanguage}.js`), module(defaults));
  writeFileSync(
    join(dist, 'i18n', `${pack.defaultLanguage}.d.ts`),
    declaration('Record<string, string>'),
  );
  if (others.length > 0) {
    const out = join(i18nPackage, 'dist');
    rmSync(out, { recursive: true, force: true });
    mkdirSync(out, { recursive: true });
    for (const language of others) {
      writeFileSync(join(out, `${language}.json`), json(pack.i18n[language]));
      writeFileSync(join(out, `${language}.js`), module(pack.i18n[language]));
      writeFileSync(join(out, `${language}.d.ts`), declaration('Record<string, string>'));
    }
  }
  return [];
}

export function specText(specRoot: string): Record<string, Record<string, string>> {
  const dir = join(specRoot, 'i18n');
  const out: Record<string, Record<string, string>> = {};
  for (const file of readdirSync(dir)
    .filter((f) => f.endsWith('.yaml'))
    .toSorted()) {
    const language = file.slice(0, -'.yaml'.length);
    out[language] = parseYaml(readFileSync(join(dir, file), 'utf8')) as Record<string, string>;
  }
  return out;
}

/**
 * Writes the spec's standard text as packs write their default language:
 * `<spec>/dist/i18n/<lang>.{json,js,d.ts}`, the entry points `@opencharacter/spec/i18n/<lang>`.
 * Returns the languages written.
 */
export function writeSpecText(specRoot: string): string[] {
  const text = specText(specRoot);
  const out = join(specRoot, 'dist', 'i18n');
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  for (const [language, messages] of Object.entries(text)) {
    writeFileSync(join(out, `${language}.json`), json(messages));
    writeFileSync(join(out, `${language}.js`), module(messages));
    writeFileSync(join(out, `${language}.d.ts`), declaration('Record<string, string>'));
  }
  return Object.keys(text);
}

const identifier = (id: string) => `p${id.replace(/[^a-zA-Z0-9]/g, '_')}`;

export function writePacksBundle(root: string, built: BuiltPack[]): void {
  const dir = join(root, 'packages', 'packs', 'dist');
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  const lines = [
    '// Generated by pnpm build:packs. Do not edit.',
    ...built.map((p) => `import ${identifier(p.id)} from '@opencharacter/${p.id}';`),
    '',
    'export const packs = {',
    ...built.map((p) => `  '${p.id}': ${identifier(p.id)},`),
    '};',
    '',
    'export default Object.values(packs);',
    '',
  ];
  writeFileSync(join(dir, 'index.js'), lines.join('\n'));
  writeFileSync(
    join(dir, 'index.d.ts'),
    "// Generated by pnpm build:packs. Do not edit.\nimport type { PackRelease } from '@opencharacter/engine';\nexport declare const packs: Record<string, PackRelease>;\ndeclare const all: PackRelease[];\nexport default all;\n",
  );
  mkdirSync(join(dir, 'i18n'), { recursive: true });
  const languages = [...new Set(built.map((p) => p.defaultLanguage))].toSorted();
  for (const language of languages) {
    const withIt = built.filter((p) => p.defaultLanguage === language);
    const text = Object.fromEntries(withIt.map((p) => [p.id, p.i18n[language] ?? {}]));
    writeFileSync(join(dir, 'i18n', `${language}.json`), json(text));
    writeFileSync(
      join(dir, 'i18n', `${language}.js`),
      [
        '// Generated by pnpm build:packs. Do not edit.',
        ...withIt.map(
          (p) => `import ${identifier(p.id)} from '@opencharacter/${p.id}/i18n/${language}';`,
        ),
        '',
        'export default {',
        ...withIt.map((p) => `  '${p.id}': ${identifier(p.id)},`),
        '};',
        '',
      ].join('\n'),
    );
    writeFileSync(
      join(dir, 'i18n', `${language}.d.ts`),
      declaration('Record<string, Record<string, string>>'),
    );
  }
}

export function readJson(file: string): unknown {
  return JSON.parse(readFileSync(file, 'utf8'));
}

